"""M5 (Integration, Experiments, Paper): put everyone's parts together and produce the result tables.

Run (toy):  python team/M5_integration/run_m5.py
Real:       python team/M5_integration/run_m5.py --docs data/hotpot/docs.json --questions data/hotpot/questions.json \
                --ner spacy --coref fastcoref --relation rebel --embedder sbert --llm ollama
Output:     team/M5_integration/outputs/results_tables.md, predictions.csv, error_analysis_sheet.csv
"""
import argparse
import os
import subprocess
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from _common import ROOT, header, in_root                             # noqa: E402

from kgrag.config import Config                                       # noqa: E402
from kgrag.contracts import check_c1, check_c3, check_c4              # noqa: E402
from kgrag.data import load_docs, load_questions                                 # noqa: E402
from kgrag.evaluation.errors import write_error_sheet                 # noqa: E402
from kgrag.evaluation.metrics import summarise                        # noqa: E402
from kgrag.evaluation.runner import run_all, save_rows                # noqa: E402
from kgrag.factory import build_everything                            # noqa: E402
from kgrag.generation.cache import CachedLLM                          # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "outputs")


def md_table(summary, group="all"):
    lines = ["| System | n | EM | EM 95% CI | F1 | Supp. recall | Abstain |", "|---|---|---|---|---|---|---|"]
    for s, groups in summary.items():
        if group in groups:
            m = groups[group]
            lines.append(f"| {s} | {m['n']} | {m['EM']:.2f} | ({m['EM_CI'][0]:.2f}, {m['EM_CI'][1]:.2f}) | "
                         f"{m['F1']:.2f} | {m['SuppRecall']:.2f} | {m['Abstain']:.2f} |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--docs", default="data/toy/docs.json"); ap.add_argument("--questions", default="data/toy/questions.json")
    ap.add_argument("--ner", default="toy"); ap.add_argument("--coref", default="toy"); ap.add_argument("--relation", default="toy")
    ap.add_argument("--embedder", default="tfidf"); ap.add_argument("--llm", default="mock")
    ap.add_argument("--hops", type=int, default=2); ap.add_argument("--budget", type=int, default=120)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--skip-tests", action="store_true")
    a = ap.parse_args()
    cfg = Config(docs_path=a.docs, questions_path=a.questions, ner=a.ner, coref=a.coref, relation=a.relation,
                 embedder=a.embedder, llm=a.llm, hops=a.hops, token_budget=a.budget)
    os.makedirs(OUT, exist_ok=True)

    header("1. Contract check: do all parts fit together?")
    problems = check_c1(in_root(a.docs), in_root(a.questions))
    qs = load_questions(in_root(a.questions))[: a.limit]
    env = build_everything(cfg, docs=load_docs(in_root(a.docs)))
    problems += check_c3(env["graph_retriever"], qs[0]["question"], "GraphRetriever", "M3")
    problems += check_c3(env["vector_retriever"], qs[0]["question"], "VectorRetriever", "M4")
    problems += check_c4(env["llm"])
    print("ALL CONTRACTS OK" if not problems else "\n".join(problems))

    header("2. Running all five systems with one shared LLM (answers cached)")
    cache = CachedLLM(env["llm"], os.path.join(OUT, "llm_cache.json"))
    for s in env["systems"]:
        s.llm = cache
    print("graph:", env["kg"].stats(), "| triples:", env["stats"]["final_triples"])
    rows = run_all(env["systems"], qs)
    cache.save()
    print(f"LLM cache: {cache.hits} reused, {cache.misses} new calls")

    header("3. Writing the tables for the paper")
    parts = ["# Results (auto-generated by run_m5.py)\n",
             f"Settings: ner={a.ner}, coref={a.coref}, relation={a.relation}, embedder={a.embedder}, llm={a.llm}, "
             f"hops={a.hops}, budget={a.budget}, questions={len(qs)}\n", "## Table 2: Overall\n", md_table(summarise(rows))]
    for by, title in (("hops", "Table 3: By number of hops"), ("type", "Table 4: By question type")):
        sm = summarise(rows, by=by)
        parts.append(f"\n## {title}\n")
        for g in sorted({g for v in sm.values() for g in v if g.startswith(by + "=")}):
            parts.append(f"\n**{g}**\n\n" + md_table(sm, g))
    open(os.path.join(OUT, "results_tables.md"), "w", encoding="utf-8").write("\n".join(parts) + "\n")
    save_rows(rows, os.path.join(OUT, "predictions.csv"))
    n = write_error_sheet(rows, os.path.join(OUT, "error_analysis_sheet.csv"))
    print(md_table(summarise(rows)))
    print(f"\nwrote results_tables.md, predictions.csv, error_analysis_sheet.csv ({n} failures for the team to label, ~20 each)")

    if not a.skip_tests:
        header("4. Running the project tests")
        r = subprocess.run([sys.executable, os.path.join(ROOT, "tests", "test_toy.py")], capture_output=True, text=True, cwd=ROOT)
        print(r.stdout.strip() or r.stderr.strip())


if __name__ == "__main__":
    main()
